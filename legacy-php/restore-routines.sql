CREATE PROCEDURE `EXPIRY`()
NO SQL
BEGIN
SELECT p_id,sup_id,med_id,p_qty,p_cost,pur_date,mfg_date,exp_date
FROM purchase
WHERE exp_date BETWEEN CURDATE() AND DATE_SUB(CURDATE(), INTERVAL -6 MONTH);
END$$

CREATE PROCEDURE `SEARCH_INVENTORY`(IN `search` VARCHAR(255))
NO SQL
BEGIN
DECLARE mid DECIMAL(6);
DECLARE mname VARCHAR(50);
DECLARE mqty INT;
DECLARE mcategory VARCHAR(20);
DECLARE mprice DECIMAL(6,2);
DECLARE location VARCHAR(30);
DECLARE exit_loop BOOLEAN DEFAULT FALSE;

DECLARE MED_CURSOR CURSOR FOR
SELECT MED_ID,MED_NAME,MED_QTY,CATEGORY,MED_PRICE,LOCATION_RACK FROM MEDS;

DECLARE CONTINUE HANDLER FOR NOT FOUND SET exit_loop=TRUE;

CREATE TEMPORARY TABLE IF NOT EXISTS T1
(medid decimal(6),medname varchar(50),medqty int,medcategory varchar(20),medprice decimal(6,2),medlocation varchar(30));

OPEN MED_CURSOR;

med_loop: LOOP
FETCH FROM MED_CURSOR INTO mid,mname,mqty,mcategory,mprice,location;

IF exit_loop THEN
LEAVE med_loop;
END IF;

IF(CONCAT(mid,mname,mcategory,location) LIKE CONCAT('%',search,'%')) THEN
INSERT INTO T1(medid,medname,medqty,medcategory,medprice,medlocation)
VALUES(mid,mname,mqty,mcategory,mprice,location);
END IF;

END LOOP med_loop;

CLOSE MED_CURSOR;

SELECT medid,medname,medqty,medcategory,medprice,medlocation FROM T1;
END$$

CREATE PROCEDURE `STOCK`()
NO SQL
BEGIN
SELECT med_id, med_name,med_qty,category,med_price,location_rack
FROM meds
WHERE med_qty<=50;
END$$

CREATE PROCEDURE `TOTAL_AMT`(IN `ID` INT, OUT `AMT` DECIMAL(8,2))
NO SQL
BEGIN
UPDATE SALES
SET S_DATE=SYSDATE(),
S_TIME=CURRENT_TIMESTAMP(),
TOTAL_AMT=(SELECT SUM(TOT_PRICE) FROM SALES_ITEMS WHERE SALES_ITEMS.SALE_ID=ID)
WHERE SALES.SALE_ID=ID;

SELECT TOTAL_AMT INTO AMT FROM SALES WHERE SALE_ID=ID;
END$$

CREATE FUNCTION `P_AMT`(`start` DATE, `end` DATE)
RETURNS DECIMAL(8,2)
NO SQL
DETERMINISTIC
BEGIN
DECLARE PAMT DECIMAL(8,2) DEFAULT 0.0;

SELECT SUM(P_COST) INTO PAMT
FROM PURCHASE
WHERE PUR_DATE >= start AND PUR_DATE<= end;

RETURN PAMT;
END$$

CREATE FUNCTION `S_AMT`(`start` DATE, `end` DATE)
RETURNS DECIMAL(8,2)
NO SQL
BEGIN
DECLARE SAMT DECIMAL(8,2) DEFAULT 0.0;

SELECT SUM(TOTAL_AMT) INTO SAMT
FROM SALES
WHERE S_DATE >= start AND S_DATE<= end;

RETURN SAMT;
END$$

